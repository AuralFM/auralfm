#!/usr/bin/env node
/**
 * Mirror the project's documentation into the Knowledge-Base vault.
 *
 * The docs live in the repo because that is where they are edited and where
 * they survive a machine. They are mirrored out because the repo is not where
 * they are *read* — the vault is, alongside every other project, and a document
 * nobody opens may as well not exist.
 *
 * Two rules make this safe to run repeatedly:
 *
 *   1. **Only files this script owns are overwritten.** Every mirrored note is
 *      stamped with a generated-from header. Anything in the folder without
 *      that stamp is left alone, so hand-written notes can sit beside the
 *      mirrors without being clobbered on the next run.
 *   2. **The repo is the source, always.** Edits made in the vault to a
 *      mirrored note will be overwritten. That is the intended direction, and
 *      the header says so on every page.
 *
 * The vault path is not hardcoded to one machine: it is looked up from
 * AURALFM_KB, then a small list of known locations, and the script exits
 * quietly rather than inventing a folder somewhere unexpected.
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const REPO = path.resolve(import.meta.dirname, "..");
const PROJECT = "AURALFM";

/** Candidate vault roots, most explicit first. */
const ROOTS = [
  process.env.AURALFM_KB,
  "/Volumes/Storage/Knowledge-Base",
  path.join(process.env.HOME || "", "Knowledge-Base"),
].filter(Boolean);

const root = ROOTS.find((p) => { try { return fs.statSync(p).isDirectory(); } catch { return false; } });
if (!root) {
  console.error("No Knowledge-Base found. Looked in:");
  for (const p of ROOTS) console.error("  " + p);
  console.error("\nSet AURALFM_KB to the vault path, or plug the drive in.");
  process.exit(1);
}

const dest = path.join(root, "04 Projects", PROJECT);

/**
 * Source file → note title.
 *
 * Titled rather than slugged, because the vault's own convention is
 * "PROJECT — Topic.md" and a folder of README.md, VISION.md, DECK.md would read
 * as a repo someone dropped in the vault rather than as notes.
 */
const DOCS = [
  ["README.md",                    "Overview"],
  ["docs/LEGAL-AND-SECURITY.md",   "Legal and Security"],
  ["docs/PRIVACY.md",              "Privacy"],
  ["docs/RECEIVERS.md",            "For Receiver Operators"],
  ["docs/TERMS.md",                "Terms"],
];

const STAMP = "<!-- generated by scripts/sync-kb.mjs -->";

/** Shell out quietly; a missing `gh` or no network must not fail the sync. */
function quiet(cmd, args) {
  try { return execFileSync(cmd, args, { cwd: REPO, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); }
  catch { return ""; }
}

// Dates come from git rather than from the clock: "synced today" is worthless
// on a note you are reading in four months, and the commit is the real answer
// to "how current is this".
const commit  = quiet("git", ["rev-parse", "--short", "HEAD"]);
const when    = quiet("git", ["log", "-1", "--format=%cs"]);
const branch  = quiet("git", ["rev-parse", "--abbrev-ref", "HEAD"]);
const remote  = quiet("git", ["remote", "get-url", "origin"]).replace(/\.git$/, "");

function header(title, source) {
  return [
    STAMP,
    `# ${PROJECT} — ${title}`,
    "",
    `> Mirrored from \`${source}\` at commit \`${commit || "unknown"}\` (${when || "date unknown"}).`,
    "> **Edit the repo, not this note** — the next sync overwrites this file.",
    "",
    "---",
    "",
  ].join("\n");
}

fs.mkdirSync(dest, { recursive: true });

let written = 0, skipped = 0, protectedCount = 0;
for (const [rel, title] of DOCS) {
  const src = path.join(REPO, rel);
  if (!fs.existsSync(src)) { console.log(`  skip  ${rel} (not in repo)`); skipped++; continue; }

  const out = path.join(dest, `${PROJECT} — ${title}.md`);
  // Refuse to overwrite anything this script did not write. A note that shares
  // a name with a mirror is far more likely to be something hand-written than
  // a stale mirror, and losing it silently would be unrecoverable.
  if (fs.existsSync(out) && !fs.readFileSync(out, "utf8").startsWith(STAMP)) {
    console.log(`  keep  ${path.basename(out)} (hand-written, not overwritten)`);
    protectedCount++;
    continue;
  }

  // The source's own H1 is dropped: the header above already titles the note,
  // and two headings make the vault's outline pane show every page twice.
  const body = fs.readFileSync(src, "utf8").replace(/^#\s+.*\n+/, "");
  fs.writeFileSync(out, header(title, rel) + body);
  written++;
}

// ── the hub note ─────────────────────────────────────────────────────────────
const issues = quiet("gh", ["issue", "list", "--state", "open", "--limit", "50",
                            "--json", "number,title", "--jq",
                            '.[] | "| [#\\(.number)](ISSUEURL\\(.number)) | \\(.title) |"'])
  .replaceAll("ISSUEURL", `${remote}/issues/`);
const closedCount = quiet("gh", ["issue", "list", "--state", "closed", "--limit", "300",
                                 "--json", "number", "--jq", "length"]);
const openCount = issues ? issues.split("\n").filter(Boolean).length : 0;

const links = DOCS
  .filter(([rel]) => fs.existsSync(path.join(REPO, rel)))
  .map(([, title]) => `- [[${PROJECT} — ${title}]]`)
  .join("\n");

const hub = `${STAMP}
# 📻 ${PROJECT} — Command Center

**Maintainer:** Melton Bell III
**Repo:** [${remote.replace(/^https:\/\/github\.com\//, "")}](${remote})
**Branch:** \`${branch}\` · **Commit:** \`${commit}\` (${when})
**Position:** Offline-first. No backend of our own. Collects nothing.

> A window onto the world you can listen to.

---

## 🚧 The thing blocking everything

**Nobody else can install this app.** There is no code signing (#4) and no
release (#14), so there is exactly one user. Every feature is being built for an
audience of one until those land, and both need an Apple Developer account —
which is a purchase, not an engineering task.

---

## 📂 Notes

${links}

---

## 🐛 Open issues (${openCount} open, ${closedCount} closed)

| | |
|---|---|
${issues || "| — | none, or `gh` unavailable |"}

---

## 🧭 What it is

A photoreal globe you listen to: **38,342 internet radio stations** and **837
borrowed KiwiSDR shortwave receivers**, on an Earth with a correct day/night
terminator, live cloud cover, NASA city lights, 5,044 stars and 89
constellations. Geohash presence and public chat ride Nostr on bitchat's shared
convention — no account, no server of ours.

## ⚠️ Standing constraints

- **Volunteer infrastructure is borrowed, not owned.** Celestrak IP-blocked this
  project once and three KiwiSDRs stopped answering after over-probing. Anything
  that polls someone else's service stays off by default and behind a backoff.
- **Licences to re-check the moment money is involved:** the Noun Project icons
  (both bought and verified — but §3.A caps resale at 1,000 units per licence,
  and two licences to two different icons do not raise that to 2,000),
  TeleGeography (unanswered), and any CC-BY-NC source that has crept in.
- **Measure, do not assert.** Every claim in these notes is traceable to a
  commit; where something is unknown the notes say so rather than filling the box.

---

*This note is generated. Edit \`scripts/sync-kb.mjs\` in the repo, or add your own
notes to this folder under a different filename — the sync leaves those alone.*
`;

const hubPath = path.join(dest, `${PROJECT} — Command Center.md`);
if (fs.existsSync(hubPath) && !fs.readFileSync(hubPath, "utf8").startsWith(STAMP)) {
  console.log(`  keep  ${path.basename(hubPath)} (hand-written, not overwritten)`);
  protectedCount++;
} else {
  fs.writeFileSync(hubPath, hub);
  written++;
}

console.log(`\n${dest}`);
console.log(`  ${written} written, ${skipped} missing, ${protectedCount} left alone`);
