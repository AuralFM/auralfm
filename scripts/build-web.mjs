#!/usr/bin/env node
/**
 * Build AuralFM for the web into dist-web/.
 *
 *   npm run web
 *
 * The web version is the desktop's own pages — Explore and Settings, unchanged —
 * with web/bridge.js standing in for the Electron main process behind
 * `window.auralfm`. The modules the bridge needs from src/ (the catalogue,
 * palettes, strings, weather, prices, the ISS, space weather) are the desktop's
 * own files, wrapped here as CommonJS-in-a-function so a browser can run them.
 * Nothing is copied by hand, so the web cannot drift from the app.
 *
 * Refuses to build without the generated data the page needs, for the same
 * reason `npm run dist` does: a site with no station list opens to nothing.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const R = (...p) => path.join(ROOT, ...p);
const OUT = R("dist-web");
const { version } = JSON.parse(fs.readFileSync(R("package.json"), "utf8"));
const BUILD = Date.now().toString(36);

const NEEDED = ["data/stations.min.json", "assets/sky.json", "src/renderer/vendor/globe.gl.min.js"];
const missing = NEEDED.filter((f) => !fs.existsSync(R(f)));
if (missing.length) {
  console.error(`web: missing ${missing.join(", ")} — run npm run crawl, npm run sky and npm run vendor first`);
  process.exit(1);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "web"), { recursive: true });
const copy = (from, to = from) => fs.cpSync(R(from), path.join(OUT, to), { recursive: true });

// ── the desktop modules, wrapped ─────────────────────────────────────────────
// Order does not matter (require is lazy), but every module a wrapped one
// requires must be in this list or be one of the shims below.
const MODULES = ["backoff", "useragent", "geo", "prefs", "palettes", "i18n", "safehost",
                 "catalog", "weather", "markets", "iss", "space", "clouds", "wspr", "news",
                 "docs"];
const EXPOSE = ["geo", "prefs", "palettes", "i18n", "catalog", "weather", "markets", "iss", "space",
                "clouds", "wspr", "news", "docs"];

/**
 * The documents src/docs.js is allowed to show, carried into the bundle.
 *
 * Privacy, Terms and the licences are the three things somebody has a right to
 * read before deciding whether to trust this, and the web version shipped with
 * none of them — the reader in Settings was there, asking a bridge that
 * answered with an empty list.
 *
 * Read from the allowlist in src/docs.js rather than named again here: that
 * list is an allowlist on purpose, because BUSINESS.md and DECK.md live in the
 * same folder, and a second copy of it is a second place to get that wrong.
 *
 * Inlined rather than fetched. They are 30 KB against 13 MB, it keeps them
 * readable with no network, and it saves the service worker three more URLs.
 */
const docFiles = Object.fromEntries(
  [...fs.readFileSync(R("src/docs.js"), "utf8").matchAll(/file:\s*"([^"]+)"/g)]
    .map(([, f]) => [f.split("/").pop(), fs.readFileSync(R(f), "utf8")]));
if (Object.keys(docFiles).length < 3) {
  console.error("web: src/docs.js no longer lists three documents — check the allowlist");
  process.exit(1);
}

const wrapped = MODULES.map((id) => {
  const src = fs.readFileSync(R("src", `${id}.js`), "utf8");
  for (const name of src.matchAll(/require\(["']([^"']+)["']\)/g)) {
    const dep = name[1];
    const ok = dep === "node:fs" || dep === "node:path" || dep === "../package.json"
      || MODULES.includes(dep.replace(/^\.\//, ""));
    if (!ok) throw new Error(`web: src/${id}.js requires ${dep}, which the web build does not provide`);
  }
  return `factories[${JSON.stringify(id)}] = function (module, exports, require, process, __dirname) {\n${src}\n};`;
}).join("\n\n");

fs.writeFileSync(path.join(OUT, "web", "modules.js"), `// Generated by scripts/build-web.mjs from src/. Do not edit.
window.AuralMods = (() => {
  "use strict";
  const files = ${JSON.stringify(docFiles)};
  const base = (p) => String(p).split("/").pop();
  const shims = {
    "node:fs": {
      existsSync: (p) => base(p) in files,
      readFileSync: (p) => {
        if (!(base(p) in files)) throw new Error("ENOENT " + p);
        return files[base(p)];
      },
    },
    "node:path": { join: (...a) => a.join("/") },
    "../package.json": { version: ${JSON.stringify(version)} },
  };
  const factories = {}, cache = {};
  function require(name) {
    if (name in shims) return shims[name];
    const id = name.replace(/^\\.\\//, "");
    if (id in cache) return cache[id];
    if (!(id in factories)) throw new Error("web build: no module " + name);
    const module = { exports: {} };
    cache[id] = module.exports;
    factories[id](module, module.exports, require, { env: {} }, "src");
    return (cache[id] = module.exports);
  }

${wrapped}

  const out = { files, version: ${JSON.stringify(version)} };
  for (const id of ${JSON.stringify(EXPOSE)}) out[id] = require("./" + id);
  return out;
})();
`);

// ── messaging, bundled ───────────────────────────────────────────────────────
// The desktop's Nostr modules need @noble and a few Node built-ins, so they are
// bundled rather than wrapped: node:crypto, node:fs and node:path resolve to the
// browser stand-ins in web/shims/, and Buffer is injected where it is named.
const { build } = await import("esbuild");
const SHIM = { "node:crypto": "crypto.js", "node:fs": "fs.js", "node:path": "path.js" };
await build({
  entryPoints: [R("web", "messaging.js"), R("web", "live.js")],
  outdir: path.join(OUT, "web"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  // satellite.js publishes only import and module-sync entry points; module-sync
  // is the one Node uses for require(), so it is the one the desktop code gets.
  conditions: ["module-sync"],
  inject: [R("web", "shims", "buffer.js")],
  banner: { js: "// Generated by scripts/build-web.mjs from src/ and web/. Do not edit." },
  logLevel: "warning",
  plugins: [{
    name: "node-shims",
    setup(b) {
      // satellite.js loads its optional WebAssembly engine lazily through these
      // imports. AuralFM only uses the plain JavaScript SGP4 functions, so the
      // engine is replaced with nothing rather than shipped.
      b.onResolve({ filter: /^#wasm-/ }, () => ({ path: "wasm", namespace: "empty" }));
      b.onLoad({ filter: /.*/, namespace: "empty" }, () => ({ contents: "export default {};" }));
      b.onResolve({ filter: /^node:(crypto|fs|path)$/ }, (args) => ({ path: R("web", "shims", SHIM[args.path]) }));
      b.onResolve({ filter: /^node:/ }, (args) => ({ errors: [{ text: `web: ${args.path} has no browser stand-in` }] }));
    },
  }],
});

// ── the pages ────────────────────────────────────────────────────────────────
/**
 * What the web page may reach. Stricter than "anything https" for fetches: the
 * few services the bridge calls, and nothing else. Audio is the exception — a
 * station can be hosted anywhere, so media may come from any https origin.
 */
const CSP = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data: blob: https://gibs.earthdata.nasa.gov",
  "media-src https: blob:",
  "worker-src blob: 'self'",
  "frame-src 'self'",
  "connect-src 'self' https://api.open-meteo.com https://api.coingecko.com "
    + "wss://ws-feed.exchange.coinbase.com https://api.wheretheiss.at "
    + "https://services.swpc.noaa.gov https://*.api.radio-browser.info "
    // Chat relays are chosen by where the station is, so any secure socket.
    + "wss: https://celestrak.org https://db1.wspr.live",
].join("; ");

/**
 * The logo for the toolbar: the globe mark and the AURAL.FM wordmark, from
 * web/assets/auralfm-logo.svg (bone; -onyx.svg is the same drawing in onyx).
 * Its fill becomes currentColor, so the theme picks bone on dark and onyx on
 * light (web/web.css, .brand) from one drawing.
 */
function toolbarLogo() {
  const svg = fs.readFileSync(R("web", "assets", "auralfm-logo.svg"), "utf8");
  const paths = svg.match(/<path [^>]*\/>/g) || [];
  if (paths.length !== 2) throw new Error(`web: expected 2 paths in the logo (wordmark, globe mark), found ${paths.length}`);
  const view = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (!view) throw new Error("web: the logo has no viewBox");
  // currentColor, so web.css picks bone or onyx by theme from one drawing.
  const inked = paths.map((p) => p.replace(/fill="#[0-9A-Fa-f]{3,8}"/, 'fill="currentColor"')).join("");
  return `<svg viewBox="${view}" aria-hidden="true" focusable="false">${inked}</svg>`;
}

function page(srcName, outName, { title, before, beforeScript, after = {}, logo = false }) {
  let html = fs.readFileSync(R("src", "renderer", srcName), "utf8");
  const csp = /<meta http-equiv="Content-Security-Policy"[\s\S]*?>/;
  if (!csp.test(html)) throw new Error(`web: no CSP meta in ${srcName}`);
  html = html.replace(csp, `<meta http-equiv="Content-Security-Policy" content="${CSP}">`);
  html = html.replaceAll("../../assets/", "assets/");
  html = html.replace(/<title>[^<]*<\/title>/, `<title>${title}</title>
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#0C0B0B">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<!-- "black", not "black-translucent": that mode sizes the installed window to
     the screen minus the top inset but still anchors it at the top, stranding a
     strip at the bottom that the page can never paint — the band under the tab
     bar. It is not reachable from CSS, which is why dvh, fixed insets and
     measured heights all failed to close it. Baked in when the icon is added,
     so an existing icon has to be removed and re-added to pick this up. -->
<meta name="apple-mobile-web-app-status-bar-style" content="black">
<meta name="apple-mobile-web-app-title" content="AuralFM">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="assets/icons/icon-180.png">
<link rel="icon" href="favicon.ico" sizes="48x48">
<link rel="icon" href="favicon.svg" type="image/svg+xml">`);
  // After the page's own stylesheet, so an override wins where the two are
  // equally specific rather than losing to source order.
  if (!html.includes("</head>")) throw new Error(`web: ${srcName} has no </head>`);
  html = html.replace("</head>", `<link rel="stylesheet" href="web/web.css">\n</head>`);
  const anchor = `<script src="${beforeScript}"></script>`;
  if (!html.includes(anchor)) throw new Error(`web: ${srcName} has no ${anchor}`);
  html = html.replace(anchor, before.map((s) => `<script src="${s}"></script>`).join("\n") + "\n" + anchor);
  // Scripts that must run after the page's own parts but before it starts.
  for (const [at, scripts] of Object.entries(after)) {
    const tag = `<script src="${at}"></script>`;
    if (!html.includes(tag)) throw new Error(`web: ${srcName} has no ${tag}`);
    html = html.replace(tag, scripts.map((s) => `<script src="${s}"></script>`).join("\n") + "\n" + tag);
  }
  if (logo) {
    const bar = `<div class="toolbar">`;
    if (!html.includes(bar)) throw new Error(`web: ${srcName} has no toolbar for the logo`);
    html = html.replace(bar, `${bar}\n  <span class="brand" role="img" aria-label="AuralFM">${toolbarLogo()}</span>`);
  }
  for (const f of DESKTOP_ONLY) html = html.replaceAll(`<script src="${f}"></script>\n`, "");
  // Every script and stylesheet carries this build's stamp, so a browser that
  // cached the last version fetches the new one instead of mixing the two.
  html = html.replace(/(<script src="[^"?]+)"/g, `$1?v=${BUILD}"`)
             .replace(/(<link rel="stylesheet" href="[^"?]+)"/g, `$1?v=${BUILD}"`);
  fs.writeFileSync(path.join(OUT, outName), html);
}

/**
 * Renderer scripts the web version has no use for.
 *
 * kiwi.js speaks a KiwiSDR's ws://, which an https page may not open, and the
 * bridge stubs shortwave out entirely — so the two of them were 51 KB of dead
 * JavaScript fetched, parsed and run on every launch, wireShortwave() included,
 * for a feature that cannot exist here. popover.js and splash.js belong to
 * desktop windows there is no equivalent of: no page ever loaded them, and the
 * service worker was precaching both onto people's phones.
 *
 * Dropped from the copy and from the pages that referenced them.
 */
const DESKTOP_ONLY = ["kiwi.js", "explore-shortwave.js", "popover.js", "splash.js"];

page("explore.html", "index.html", {
  title: "AuralFM",
  beforeScript: "errors.js",
  // levels.js before the bridge: the card's waveform is measured from a private
  // copy of the stream, exactly as the desktop's popover does it.
  before: ["web/modules.js", "web/messaging.js", "web/live.js", "levels.js", "web/bridge.js", "web/sheet.js"],
  after: { "explore.js": ["web/after.js", "web/rail-sheet.js", "web/phone-bar.js"] },
  logo: true,
});
page("settings.html", "settings.html", {
  title: "AuralFM Settings",
  beforeScript: "errors.js",
  before: ["web/modules.js", "web/messaging.js", "web/bridge.js", "web/settings-web.js"],
});

// ── everything the pages load ────────────────────────────────────────────────
for (const f of fs.readdirSync(R("src", "renderer"))) {
  if (f.endsWith(".js") && !DESKTOP_ONLY.includes(f)) copy(`src/renderer/${f}`, f);
}
copy("src/renderer/vendor", "vendor");
for (const f of ["bridge.js", "sheet.js", "rail-sheet.js", "phone-bar.js", "after.js", "web.css", "settings-web.js"]) copy(`web/${f}`, `web/${f}`);

// ── proxy routes ─────────────────────────────────────────────────────────────
// Google News does not let a web page read it, so here.now fetches it for the
// page from the site's own address. A plain GET of public data: no secrets, no
// account variables. `/prefix/*` forwards the rest of the path. here.now allows
// 100 requests an hour per visitor by default, which headlines — fetched only
// while the panel is open, and cached for 15 minutes — come nowhere near.
// Every route names the app, because saying who is asking is polite.
const UA = { "User-Agent": `AuralFM/${version} (+https://github.com/meltonbell3/auralfm)` };
// scripts/serve-web.mjs reads this same file to stand in for here.now locally.
fs.mkdirSync(path.join(OUT, ".herenow"), { recursive: true });
/**
 * The world headlines' feeds, one route each, from the list in src/news.js —
 * read, not copied, so a feed added there cannot be missing here. A missing
 * route is not an error anywhere: it is a 404 that reads as "no headlines".
 *
 * And a higher ceiling than here.now's default 100 an hour per IP. World asks
 * four feeds at once; a person testing from one phone passed 100 in an
 * afternoon. 400 still stops anything that loops.
 */
const { WORLD_FEEDS } = createRequire(import.meta.url)(R("src/news.js"));
if (!Array.isArray(WORLD_FEEDS) || WORLD_FEEDS.length < 2) {
  console.error("web: src/news.js exports no WORLD_FEEDS — world headlines would have no routes");
  process.exit(1);
}
const LIMIT = "400/hour/ip";
fs.writeFileSync(path.join(OUT, ".herenow", "proxy.json"), JSON.stringify({
  proxies: {
    "/api/news": { upstream: "https://news.google.com/rss", method: "GET", headers: UA, rateLimit: LIMIT },
    "/api/news/*": { upstream: "https://news.google.com/rss", method: "GET", headers: UA, rateLimit: LIMIT },
    ...Object.fromEntries(WORLD_FEEDS.map((f) =>
      [`/api/feeds/${f.route}`, { upstream: f.url, method: "GET", headers: UA, rateLimit: LIMIT }])),
  },
}, null, 2));
copy("assets/fonts", "assets/fonts");
copy("assets/sky.json", "assets/sky.json");
copy("data/stations.min.json", "data/stations.min.json");
fs.mkdirSync(path.join(OUT, "assets", "generated"), { recursive: true });
// The Dock previews are loaded by Settings even while its App icon section is
// hidden, so they ship too; they are small.
const dockIcons = fs.existsSync(R("assets", "generated"))
  ? fs.readdirSync(R("assets", "generated")).filter((f) => /^dock-.*\.png$/.test(f)) : [];
for (const f of ["favicon.png", "app-512.png", ...dockIcons]) {
  if (fs.existsSync(R("assets", "generated", f))) copy(`assets/generated/${f}`, `assets/generated/${f}`);
}

// ── the home screen ──────────────────────────────────────────────────────────
// Full-bleed icons from scripts/make-icons.js (iOS rounds them itself), and the
// manifest that lets the site open on its own, without Safari's bars.
fs.mkdirSync(path.join(OUT, "assets", "icons"), { recursive: true });
for (const px of [180, 192, 512]) {
  const src = R("assets", "generated", `ios-${px}.png`);
  if (!fs.existsSync(src)) throw new Error(`web: missing ${path.relative(ROOT, src)} — run npm run icons`);
  fs.copyFileSync(src, path.join(OUT, "assets", "icons", `icon-${px}.png`));
}

/**
 * The names browsers ask for without being told.
 *
 * The page names its icons, but a lot of requests never read the page: iOS
 * asks for /apple-touch-icon.png and its -precomposed and 120x120 siblings
 * when a link is shared or bookmarked, and anything that wants a favicon asks
 * for /favicon.ico. Each was a 404 in the site's analytics — sixteen in a week.
 * The touch icons are the home-screen icon itself, so a link and the installed
 * app never show two different pictures; iOS scales the 180 down for 120.
 *
 * The favicon is the brand's ring mark (assets/brand, exported from the design
 * file): SVG for browsers that take it, and an .ico for the ones that do not.
 */
for (const name of ["apple-touch-icon.png", "apple-touch-icon-precomposed.png",
                    "apple-touch-icon-120x120.png", "apple-touch-icon-120x120-precomposed.png"]) {
  fs.copyFileSync(path.join(OUT, "assets", "icons", "icon-180.png"), path.join(OUT, name));
}
for (const f of ["favicon.ico", "favicon.svg"]) fs.copyFileSync(R("assets", "brand", f), path.join(OUT, f));
fs.writeFileSync(path.join(OUT, "manifest.webmanifest"), JSON.stringify({
  name: "AuralFM",
  short_name: "AuralFM",
  description: "A globe you listen to: live radio from 12,000 places, and the sky over them.",
  // A stable identity, so the icon somebody added stays the same app when the
  // start URL or scope ever changes.
  id: "/",
  start_url: "./",
  scope: "./",
  display: "standalone",
  orientation: "any",
  /**
   * The two things worth doing without opening the app first, on the icon's
   * long press: somewhere else, and what you kept.
   */
  shortcuts: [
    { name: "Take me somewhere", short_name: "Somewhere", url: "./?go=somewhere" },
    { name: "Favorites", short_name: "Favorites", url: "./?go=favorites" },
  ],
  background_color: "#0C0B0B",
  theme_color: "#0C0B0B",
  icons: [
    { src: "assets/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
    { src: "assets/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
    { src: "assets/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
}, null, 2));

/**
 * The service worker, stamped with this build and told what the shell is.
 *
 * The list is the app's own files plus the two big local sources — the globe's
 * textures and the station catalogue — because those are what make a cold
 * start slow. It is written from what actually landed in dist-web, so a file
 * that was renamed cannot quietly fall out of the cache.
 */
{
  const shell = ["./", "index.html", "manifest.webmanifest", "web/web.css"];
  const walk = (dir, base = "") => {
    for (const e of fs.readdirSync(path.join(OUT, dir), { withFileTypes: true })) {
      const rel = `${base}${e.name}`;
      if (e.isDirectory()) walk(path.join(dir, e.name), `${rel}/`);
      else if (/\.(js|json|jpg|png|svg|woff2)$/.test(e.name)) shell.push(`${dir}/${rel}`.replace(/^\.\//, ""));
    }
  };
  for (const f of fs.readdirSync(OUT)) if (f.endsWith(".js")) shell.push(f);
  walk("web"); walk("vendor"); walk("data"); walk("assets/icons");
  const stamped = fs.readFileSync(R("web", "sw.js"), "utf8")
    .replace("__BUILD__", BUILD)
    // The page asks for its own scripts and stylesheet with this build's stamp,
    // so they are cached under exactly that; everything else keeps a plain name
    // because that is how the code asks for it.
    .replace("__SHELL__", JSON.stringify(
      shell.map((u) => (/\.(js|css)$/.test(u) ? `${u}?v=${BUILD}` : u)), null, 2));
  fs.writeFileSync(path.join(OUT, "sw.js"), stamped);
}

const size = (dir) => fs.readdirSync(dir, { withFileTypes: true }).reduce((n, e) =>
  n + (e.isDirectory() ? size(path.join(dir, e.name)) : fs.statSync(path.join(dir, e.name)).size), 0);
console.log(`web: dist-web/ built — ${(size(OUT) / 1e6).toFixed(1)} MB, AuralFM ${version}`);
