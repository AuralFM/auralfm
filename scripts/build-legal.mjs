#!/usr/bin/env node
/**
 * The website's Privacy Policy and Terms of Service, from the app's own files.
 *
 *   node scripts/build-legal.mjs          writes privacy/ and terms/ on both sites
 *   node scripts/build-legal.mjs --check  exits 1 if any is out of date
 *
 * They lived only in the app, under Settings — a policy somebody cannot read
 * before installing is not much of a policy. So auralfm.xyz publishes them too,
 * and they are *generated*, never written twice: the text is docs/PRIVACY.md and
 * docs/TERMS.md, rendered by src/docs.js, the same renderer and the same files
 * the app reads. The page around them (header, footer, the ring mark) is taken
 * from home/support/index.html, so every page on the site shares one chrome.
 *
 * They are published twice: on auralfm.xyz, and on docs.auralfm.xyz, which is
 * public while the homepage is still behind a password — a policy has to be
 * readable by anyone, before anything else is. Each copy wears its own site's
 * chrome, so its header and footer lead back into the site it is on.
 *
 * The audit runs --check, so a change to either document that is not rebuilt
 * here fails the build instead of leaving the website saying something else.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const R = (...p) => path.join(ROOT, ...p);
const docs = createRequire(import.meta.url)(R("src/docs.js"));
const check = process.argv.includes("--check");

const PAGES = [
  { id: "privacy", dir: "privacy", title: "Privacy", kicker: "AuralFM — Privacy Policy",
    description: "What AuralFM stores, what it contacts, and what it never collects. No accounts, no analytics in the app, nothing about what you play." },
  { id: "terms", dir: "terms", title: "Terms", kicker: "AuralFM — Terms of Service",
    description: "The terms for using AuralFM, deliberately short." },
];

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// Each site's chrome, as it looks from a page one folder down.
const SITES = [
  { dir: "home", origin: "https://auralfm.xyz", from: "home/support/index.html",
    // The support page marks itself current; here nothing in the bar is.
    shift: (h) => h.replace(/ aria-current="page"/g, "")
      .replace(/<a (class="cell" )?href="\.\/">Support<\/a>/g, '<a $1href="../support/">Support</a>') },
  { dir: "docs-site", origin: "https://docs.auralfm.xyz", from: "docs-site/index.html",
    shift: (h) => h.replace(/ aria-current="page"/g, "")
      .replace(/(href|src)="(assets\/|aural\.css|aural\.js|privacy\/|terms\/)/g, '$1="../$2')
      .replace(/href="\.\/">Docs</g, 'href="../">Docs<') },
];

function chrome(site) {
  const html = fs.readFileSync(R(site.from), "utf8");
  const headEnd = html.indexOf('<main id="main">'), footStart = html.indexOf("</main>");
  if (headEnd < 0 || footStart < 0) throw new Error(`legal: ${site.from} has no <main id="main"> … </main>`);
  return { head: site.shift(html.slice(0, headEnd)), foot: site.shift(html.slice(footStart)) };
}

function page(site, p) {
  const doc = docs.read(p.id);
  if (!doc) throw new Error(`legal: src/docs.js has no document "${p.id}"`);
  const updated = /\*\*Last updated: ([^*]+)\*\*/.exec(doc.text)?.[1] || "";
  const url = `${site.origin}/${p.dir}/`;
  const c = chrome(site);
  const head = c.head
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(p.title)} · AuralFM</title>`)
    .replace(/(<meta name="description" content=")[^"]*"/, `$1${esc(p.description)}"`)
    .replace(/(<meta property="og:title" content=")[^"]*"/, `$1${esc(p.kicker)}"`)
    .replace(/(<meta property="og:description" content=")[^"]*"/, `$1${esc(p.description)}"`)
    .replace(/(<meta property="og:url" content=")[^"]*"/, `$1${url}"`);
  const foot = c.foot.replace(`<a href="../${p.dir}/">${p.title}</a>`, `<a href="./" aria-current="page">${p.title}</a>`);
  if (!foot.includes('aria-current="page"')) throw new Error(`legal: ${site.from}'s footer has no link to ${p.dir}/`);
  return `${head}<main id="main">
  <!-- Generated by scripts/build-legal.mjs from docs/${p.id.toUpperCase()}.md. Do not edit here. -->
  <section class="hero legal-hero grid">
    <h1 class="cell display stretch">${esc(p.title)}</h1>
    <div class="cell intro">
      <p class="label">[ ${esc(p.kicker)} ]</p>
      ${updated ? `<p class="lede">Last updated ${esc(updated)}.</p>` : ""}
      <!-- The document's own "Last updated" line is dropped below, said here once. -->
      <p class="proof">The same text the app shows under Settings. When one changes, so does the other.</p>
    </div>
  </section>
  <article class="prose grid">
    <div class="cell"><div class="body">
${doc.html.replace(/<p><strong>Last updated:[^<]*<\/strong><\/p>\s*/, "")}
    </div></div>
  </article>
${foot}`;
}

let stale = 0;
for (const site of SITES) for (const p of PAGES) {
  const rel = `${site.dir}/${p.dir}/index.html`, out = R(rel);
  const html = page(site, p);
  if (check) {
    const now = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (now !== html) { stale++; console.log(`legal: ${rel} is out of date — run node scripts/build-legal.mjs`); }
  } else {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, html);
    console.log(`legal: wrote ${rel}`);
  }
}
if (check && stale) process.exit(1);
