/**
 * What every audit file shares: paths, the verdict, and the sources they read.
 * Loaded once, so `failures` and `skipped` count the whole run.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const R = (p) => path.join(ROOT, p);
export const rel = (p) => path.relative(ROOT, p);

export let failures = 0;
export const fail = (rule, detail) => { failures++; console.log(`  FAIL  ${rule}\n        ${detail}`); };
export const pass = (rule) => console.log(`  ok    ${rule}`);
// Some things cannot be checked everywhere. The station bundle and the receiver
// list are generated by the crawl and gitignored, so on a fresh clone or in CI
// they are simply absent. Reporting that as a failure trains people to ignore a
// red run, and reporting it as a pass is a lie about what was verified.
export let skipped = 0;
// Set by `npm run dist`: files that may be absent in CI must be present in a build.
export const RELEASE = process.argv.includes("--release");
export const skip = (rule, why) => { skipped++; console.log(`  --    ${rule}\n        not checkable here: ${why}`); };
/**
 * The catalogue's own files.
 *
 * The station list, the taxonomy and the scripts that build them moved to
 * AuralFM/catalogue on 12 Oct 2026 (scripts/catalogue.mjs brings copies here).
 * The checks that read those scripts came with a fault each, and stay here,
 * reading the catalogue's checkout beside this one. Without it they say they
 * could not be run, which is not the same as passing.
 */
export const CAT = process.env.AURALFM_CATALOGUE || path.resolve(ROOT, "..", "auralfm-catalogue");
export const HAS_CAT = fs.existsSync(path.join(CAT, "scripts", "profiles.mjs"));
export const C = (p) => path.join(CAT, p);
export const NO_CAT = `the catalogue repo is not at ${CAT} (set AURALFM_CATALOGUE)`;

export const renderers = fs.readdirSync(R("src/renderer"))
  .filter((f) => f.endsWith(".html"))
  .map((f) => ({ file: R(`src/renderer/${f}`), html: fs.readFileSync(R(`src/renderer/${f}`), "utf8") }));

export const mainFiles = fs.readdirSync(R("src"))
  .filter((f) => f.endsWith(".js"))
  .map((f) => ({ file: R(`src/${f}`), src: fs.readFileSync(R(`src/${f}`), "utf8") }));


export const preload = fs.readFileSync(R("src/preload.js"), "utf8");

// The main process is src/main.js plus the modules in src/main/ it registers
// (the IPC handlers and the state store). Checks that read "main" read all of it,
// so a handler moving between those files can never make a check stop looking.
export const MAIN_FILES = ["src/main.js", ...fs.readdirSync(R("src/main"))
  .filter((f) => f.endsWith(".js")).sort().map((f) => `src/main/${f}`)];
export const main = MAIN_FILES.map((f) => fs.readFileSync(R(f), "utf8")).join("\n");

// Explore is one page split across plain scripts — explore-*.js, then explore.js
// — that share a global scope. Checks that read "Explore" read all of it, in the
// order explore.html loads it, so moving code between the parts can never make
// a check stop looking.
export const EXPLORE = "src/renderer/explore*.js";
export const EXPLORE_FILES = [...fs.readFileSync(R("src/renderer/explore.html"), "utf8")
  .matchAll(/<script src="(explore[\w-]*\.js)"/g)].map((m) => `src/renderer/${m[1]}`);
export const exploreSrc = EXPLORE_FILES.map((f) => fs.readFileSync(R(f), "utf8")).join("\n");
export const readSrc = (f) => (f === EXPLORE ? exploreSrc : fs.readFileSync(R(f), "utf8"));

export const channels = [...preload.matchAll(/ipcRenderer\.(invoke|send|on)\(\s*"([^"]+)"/g)]
  .map((m) => ({ kind: m[1], name: m[2] }));

export const { strings, LANGUAGES } = await import(pathToFileURL(R("src/i18n.js")).href).then((m) => m.default || m);
export const en = strings("en", "en");

export const pkg = JSON.parse(fs.readFileSync(R("package.json"), "utf8"));
