#!/usr/bin/env node
/**
 * The vibe directory on auralfm.xyz: every station in every vibe, by place.
 *
 *   node scripts/build-vibes.mjs          writes home/vibes/ and the homepage's vibe cards
 *   node scripts/build-vibes.mjs --check  exits 1 if any of it is behind the catalogue
 *
 * The web app lights a vibe on the globe; this is the same thing as a page you
 * can read, search and link to — no database, just the catalogue written out.
 * The vibes and their tags are src/catalog.js's VIBES, the places are its
 * vibePlaces(), so the directory and the app never disagree about what "jazz"
 * means. Every place links into the app with the vibe lit and the place
 * chosen; nothing starts playing, arriving is not the same as pressing play.
 *
 * Writes home/vibes/index.html, home/vibes/<id>/index.html, and the list of
 * vibe cards on the homepage (between the vibe-list tags), whose counts come
 * from here too — they had been typed in by hand.
 *
 * The page around the lists is home/support/index.html's, like the legal
 * pages, so every page on the site shares one header and footer.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { vibeSvg } from "./vibe-art.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const R = (...p) => path.join(ROOT, ...p);
const catalog = createRequire(import.meta.url)(R("src/catalog.js"));
const check = process.argv.includes("--check");
if (!catalog.load()) { console.error("vibes: no catalogue — run npm run catalogue"); process.exit(1); }

const APP = "https://listen.auralfm.xyz/";
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const num = (n) => n.toLocaleString("en-US");
const plural = (n, one, many = one + "s") => `${num(n)} ${n === 1 ? one : many}`;

// A station nobody gave a town lives at "Across <country>" (scripts/expand.mjs).
// Those come after every real town, as they do in the app.
const NOWHERE = /^(Across |Somewhere in |Online, no country$|Online only$)/;
// ── the data ────────────────────────────────────────────────────────────────
const VIBES = catalog.VIBES.map((v) => {
  const want = new Set(v.tags);
  const places = catalog.vibePlaces(v.id).map((p) => ({
    ...p,
    stations: catalog.placeChannels(p.i).channels
      .filter((c) => c.tags.some((t) => want.has(t.toLowerCase())))
      .map((c) => ({ id: c.id, title: c.title.trim() })).filter((c) => c.title)
      .sort((a, b) => a.title.localeCompare(b.title)),
  })).sort((a, b) => NOWHERE.test(a.title) - NOWHERE.test(b.title) || b.n - a.n || a.title.localeCompare(b.title));
  const stations = places.reduce((s, p) => s + p.n, 0);
  const countries = new Set(places.map((p) => p.country).filter(Boolean)).size;
  return { ...v, places, stations, countries };
});

// ── the chrome, one or two folders down ─────────────────────────────────────
const support = fs.readFileSync(R("home/support/index.html"), "utf8");
const cut = [support.indexOf('<main id="main">'), support.indexOf("</main>")];
if (cut.some((i) => i < 0)) throw new Error('vibes: home/support/index.html has no <main id="main"> … </main>');
function chrome(depth, { title, description, url }) {
  // The support page's links are one folder down already; deeper adds a ../.
  const deeper = (h) => depth === 1 ? h : h.replace(/(href|src)="\.\.\//g, `$1="${"../".repeat(depth)}`);
  const fix = (h) => deeper(h.replace(/ aria-current="page"/g, "")
    .replace(/<a (class="cell" )?href="\.\/">Support<\/a>/g, '<a $1href="../support/">Support</a>'));
  const head = fix(support.slice(0, cut[0]))
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(title)} · AuralFM</title>`)
    .replace(/(<meta name="description" content=")[^"]*"/, `$1${esc(description)}"`)
    .replace(/(<meta property="og:title" content=")[^"]*"/, `$1${esc(title)} · AuralFM"`)
    .replace(/(<meta property="og:description" content=")[^"]*"/, `$1${esc(description)}"`)
    .replace(/(<meta property="og:url" content=")[^"]*"/, `$1${url}"`);
  return { head, foot: fix(support.slice(cut[1])) };
}
const NUMBER = { 10: "Ten", 12: "Twelve", 15: "Fifteen", 16: "Sixteen", 17: "Seventeen", 18: "Eighteen", 20: "Twenty" };
const MARK = "<!-- Generated by scripts/build-vibes.mjs from the catalogue. Do not edit here. -->";

// ── a vibe too big for one page ─────────────────────────────────────────────
/**
 * Rock is 6,177 stations in 2,603 places: 1.8 MB of page and twenty-five
 * thousand elements on a phone (Melton's list, 6 Oct 2026). A vibe over
 * SPLIT_OVER stations is given a page per part of the world, and its own page
 * becomes the way in to them, with its busiest places as a taste.
 *
 * A country goes where most of its stations are, so Russia is not cut at the
 * Urals nor Portugal at the Azores. The boxes are rough on purpose (this is a
 * way to make four pages out of one, not a ruling on where Europe ends), and
 * Africa is read from the taxonomy's own list, because a box that puts Tunis
 * in Europe is wrong.
 */
const SPLIT_OVER = 3000;
const REGIONS = [
  { id: "americas", name: "The Americas" },
  { id: "europe", name: "Europe" },
  { id: "africa-middle-east", name: "Africa & the Middle East" },
  { id: "asia-pacific", name: "Asia & the Pacific" },
  { id: "online", name: "Online, no country" },
];
const taxonomySrc = fs.readFileSync(R("src/taxonomy.js"), "utf8");
const AFRICA = new Set([...(taxonomySrc.match(/const AFRICA = \[([\s\S]*?)\];/)?.[1] || "").matchAll(/"([^"]+)"/g)].map((m) => m[1]));
const IN_EUROPE = new Set(["Cyprus", "Malta", "Gibraltar", "Türkiye", "Turkey", "Madeira", "Azores", "Canary Islands"]);
// West of 60°E and north of 43° is Europe as far as the Urals, so Russia's
// stations, most of them west of there, carry the country with them.
const box = (lat, lon) => lon < -130 && lat < 15 ? "asia-pacific"      // Tonga, the Samoas, Tahiti: the Pacific, not the Americas
  : lon < -25 ? "americas" : lon >= 60 ? "asia-pacific"
  : (lat >= 36 && lon < 45) || (lat >= 43 && lon < 60) ? "europe" : "africa-middle-east";
function regionsOf(places) {
  const votes = new Map();
  for (const p of places) {
    if (!p.country) continue;
    const v = votes.get(p.country) || {};
    const b = box(p.lat, p.lon);
    v[b] = (v[b] || 0) + p.n;
    votes.set(p.country, v);
  }
  const of = (country) => !country ? "online" : AFRICA.has(country) ? "africa-middle-east" : IN_EUROPE.has(country) ? "europe"
    : Object.entries(votes.get(country) || {}).sort((a, b) => b[1] - a[1])[0]?.[0] || "online";
  return REGIONS.map((r) => ({ ...r, places: places.filter((p) => of(p.country) === r.id) })).filter((r) => r.places.length);
}

// ── /vibes/<id>/ (and /vibes/<id>/<region>/) ────────────────────────────────
const placeRow = (v) => (p) => {
    const href = `${APP}?place=${encodeURIComponent(p.title)}&country=${encodeURIComponent(p.country)}&vibe=${v.id}`;
    // Folded like the app's search: "sao paulo" finds São Paulo.
    const q = [p.title, p.country, ...p.stations.map((c) => c.title)].join(" ").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
    /**
     * A timetable row, not a paragraph (Melton, 4 Oct: the run-on list of names
     * separated by dots was not legible). The place on the left, its stations
     * on the right, one to a line and numbered; a name that is really a slogan
     * is cut to one line with the whole of it in its title. The first eight
     * show, the rest fold under "more", so Paris does not push Dakar off the page.
     *
     * Each name opens in place, as it does in the app (Melton, 5 Oct): what the
     * station says about itself, its links, and "Claim this station". It is a
     * link to the station in the app, so it works with no script; home/aural.js
     * turns it into the button that opens the panel, and reads the profile from
     * the same files the app reads (listen.auralfm.xyz/data/profiles/). The row
     * is kept as short as it can be (no class, no id of its own: the link holds
     * the station's id).
     */
    const SHOW = 8;
    const item = (c) => `<li><a href="${APP}?station=${encodeURIComponent(c.id)}"><span>${esc(c.title)}</span></a></li>`;
    const first = p.stations.slice(0, SHOW), rest = p.stations.slice(SHOW);
    return `      <li class="vplace" data-q="${esc(q)}">
        <a class="vp-head" href="${esc(href)}"><b>${esc(p.title)}</b><span class="vp-meta">${esc(p.country)}${p.country ? " · " : ""}${plural(p.n, "station")}</span><span class="vp-go" aria-hidden="true">Open on the globe →</span></a>
        <div class="vp-list">
          <ol class="vst">${first.map(item).join("")}</ol>${rest.length ? `
          <details class="vp-more"><summary>${rest.length} more</summary><ol class="vst" start="${SHOW + 1}">${rest.map(item).join("")}</ol></details>` : ""}
        </div>
      </li>`;
};
const sum = (places) => ({ stations: places.reduce((n, p) => n + p.n, 0), countries: new Set(places.map((p) => p.country).filter(Boolean)).size });
const othersNav = (v, up) => `  <nav class="vibe-others grid" aria-label="Other vibes">
    <p class="cell label">[ Other vibes ]</p>
    <ul>
${VIBES.filter((o) => o.id !== v.id).map((o) => `      <li><a href="${up}${o.id}/">${esc(o.name)}</a></li>`).join("\n")}
    </ul>
  </nav>`;
const hero = (v, title, lede) => `  <section class="hero legal-hero vibe-hero grid">
    <h1 class="cell display fit stretch">${esc(title)}</h1>
    <div class="cell vibe-hero-art">${vibeSvg(v.id, "vibe-art big")}</div>
    <div class="cell intro">
      <p class="label">[ Vibe · ${esc(v.tags.slice(0, 4).join(", "))}${v.tags.length > 4 ? " and more" : ""} ]</p>
      <p class="lede">${lede}</p>
      <p class="proof">Grouped by the tags stations give themselves. Nobody ranks them and nobody
        pays to be here. Pick a place to open it on the globe, or a station to read about it.</p>
      <a class="btn" href="${APP}?vibe=${v.id}">Light it up on the globe</a>
    </div>
  </section>`;
const directory = (v, places, heading, withFilter = true) => `  <section class="directory grid" aria-labelledby="dir-title">
    <div class="cell dir-head">
      <h2 id="dir-title" class="label">[ ${esc(heading)} ]</h2>${withFilter ? `
      <label class="dir-filter">
        <span class="sronly">Filter by city, country or station</span>
        <input type="search" data-filter="#dir-list" placeholder="Filter by city, country or station"
               autocomplete="off" spellcheck="false" aria-describedby="dir-count">
      </label>
      <p class="dir-count" id="dir-count" aria-live="polite" data-total="${places.length}">${plural(places.length, "place")}</p>` : ""}
    </div>
    <ul class="vplaces" id="dir-list">
${places.map(placeRow(v)).join("\n")}
    </ul>${withFilter ? `
    <p class="cell dir-none" hidden>Nothing here matches. Try a country, or fewer letters.</p>` : ""}
  </section>`;

/** One vibe, whole. */
function vibePage(v) {
  const c = chrome(2, {
    title: `${v.name} radio`,
    description: `${plural(v.stations, "station")} playing ${v.name.toLowerCase()} in ${plural(v.places.length, "place")} across ${plural(v.countries, "country", "countries")}, live on the AuralFM globe.`,
    url: `https://auralfm.xyz/vibes/${v.id}/`,
  });
  return `${c.head}<main id="main">
  ${MARK}
${hero(v, v.name, `${plural(v.stations, "station")} in ${plural(v.places.length, "place")} across
        ${plural(v.countries, "country", "countries")}, the busiest first.`)}

${directory(v, v.places, "Every place")}

${othersNav(v, "../")}
${c.foot}`;
}
/** A vibe in parts: its own page is the way in, with its busiest places. */
function splitIndex(v, regions) {
  const c = chrome(2, {
    title: `${v.name} radio`,
    description: `${plural(v.stations, "station")} playing ${v.name.toLowerCase()} in ${plural(v.places.length, "place")} across ${plural(v.countries, "country", "countries")}, by part of the world, live on the AuralFM globe.`,
    url: `https://auralfm.xyz/vibes/${v.id}/`,
  });
  return `${c.head}<main id="main">
  ${MARK}
${hero(v, v.name, `${plural(v.stations, "station")} in ${plural(v.places.length, "place")} across
        ${plural(v.countries, "country", "countries")}. Too many for one page: pick a part of the world.`)}

  <nav class="vibe-others vibe-regions grid" aria-label="${esc(v.name)}, by part of the world">
    <p class="cell label">[ By part of the world ]</p>
    <ul>
${regions.map((r) => `      <li><a href="${r.id}/"><b>${esc(r.name)}</b><span>${plural(sum(r.places).stations, "station")} · ${plural(r.places.length, "place")}</span></a></li>`).join("\n")}
    </ul>
  </nav>

${directory(v, v.places.slice(0, 12), "The busiest places", false)}

${othersNav(v, "../")}
${c.foot}`;
}
/** One part of the world of a vibe in parts. */
function regionPage(v, r, regions) {
  const t = sum(r.places);
  const c = chrome(3, {
    title: `${v.name} radio: ${r.name}`,
    description: `${plural(t.stations, "station")} playing ${v.name.toLowerCase()} in ${plural(r.places.length, "place")} across ${plural(t.countries, "country", "countries")}: ${r.name}. Live on the AuralFM globe.`,
    url: `https://auralfm.xyz/vibes/${v.id}/${r.id}/`,
  });
  return `${c.head}<main id="main">
  ${MARK}
${hero(v, `${v.name}: ${r.name}`, `${plural(t.stations, "station")} in ${plural(r.places.length, "place")}${t.countries ? ` across
        ${plural(t.countries, "country", "countries")}` : ""}, the busiest first.`)}

${directory(v, r.places, "Every place")}

  <nav class="vibe-others grid" aria-label="${esc(v.name)}, other parts of the world">
    <p class="cell label">[ ${esc(v.name)} elsewhere ]</p>
    <ul>
      <li><a href="../">All of ${esc(v.name)}</a></li>
${regions.filter((o) => o.id !== r.id).map((o) => `      <li><a href="../${o.id}/">${esc(o.name)}</a></li>`).join("\n")}
    </ul>
  </nav>
${othersNav(v, "../../")}
${c.foot}`;
}

// ── /vibes/ and the homepage's cards ────────────────────────────────────────
/**
 * The cards, and one more that closes the grid. Seventeen vibes leave a hole in
 * any grid (it is prime), and a hole here shows as a grey block; the eighteenth
 * tile goes where the reader would go next: to every vibe from the homepage, to
 * the globe from the page that already lists them.
 */
const cards = (base, last) => [...VIBES.map((v) =>
  `      <li class="cell vibe"><a href="${base}${v.id}/">${vibeSvg(v.id)}<b>${esc(v.name)}</b><span>${num(v.stations)} stations · ${num(v.places.length)} places</span></a></li>`),
  `      <li class="cell vibe vibe-all"><a href="${last.href}"><span class="vibe-n" aria-hidden="true">${VIBES.length}</span><b>${esc(last.name)}</b><span>${esc(last.note)}</span></a></li>`].join("\n");
const ALL_HOME = { href: "vibes/", name: "Every vibe", note: "Every station · by place →" };
const ALL_INDEX = { href: APP, name: "The globe", note: "Open it and pick one →" };

function indexPage() {
  const total = VIBES.reduce((s, v) => s + v.stations, 0);
  const c = chrome(1, {
    title: "Vibes",
    description: `${NUMBER[VIBES.length] || VIBES.length} vibes across the globe, from ${VIBES.map((v) => v.name.toLowerCase()).slice(0, 3).join(", ")} to ${VIBES.at(-1).name.toLowerCase()}: ${num(total)} stations, by place.`,
    url: "https://auralfm.xyz/vibes/",
  });
  return `${c.head}<main id="main">
  ${MARK}
  <section class="hero legal-hero grid">
    <h1 class="cell display stretch">Vibes</h1>
    <div class="cell intro">
      <p class="label">[ The directory ]</p>
      <p class="lede">Lanes across the whole globe, named by people rather than by a chart. Each
        one is every station that plays it, wherever it is.</p>
      <p class="proof">A station can be in more than one: a jazz station that also talks is in both.</p>
    </div>
  </section>
  <section class="vibes grid" aria-label="Every vibe">
    <ul class="vibe-list">
${cards("", ALL_INDEX)}
    </ul>
  </section>
${c.foot}`;
}

// ── build or check ──────────────────────────────────────────────────────────
const want = new Map([[R("home/vibes/index.html"), indexPage()]]);
for (const v of VIBES) {
  if (v.stations <= SPLIT_OVER) { want.set(R("home/vibes", v.id, "index.html"), vibePage(v)); continue; }
  const regions = regionsOf(v.places);
  want.set(R("home/vibes", v.id, "index.html"), splitIndex(v, regions));
  for (const r of regions) want.set(R("home/vibes", v.id, r.id, "index.html"), regionPage(v, r, regions));
  if (!check) console.log(`vibes: ${v.id} is in parts — ${regions.map((r) => `${r.id} ${sum(r.places).stations}`).join(", ")}`);
}
const home = fs.readFileSync(R("home/index.html"), "utf8");
const list = /(<ul class="vibe-list">\n)[\s\S]*?(\n    <\/ul>)/;
if (!list.test(home)) throw new Error('vibes: home/index.html has no <ul class="vibe-list">');
want.set(R("home/index.html"), home.replace(list, `$1${cards("vibes/", ALL_HOME)}$2`));

let stale = 0;
for (const [file, html] of want) {
  const rel = path.relative(ROOT, file);
  if ((fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "") === html) continue;
  if (check) { stale++; console.log(`vibes: ${rel} is behind the catalogue — run node scripts/build-vibes.mjs`); }
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, html); console.log(`vibes: wrote ${rel}`); }
}
if (!check) for (const v of VIBES) console.log(`vibes: ${v.id} — ${v.stations} stations, ${v.places.length} places, ${v.countries} countries`);
if (check && stale) process.exit(1);
